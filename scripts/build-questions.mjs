// Reads questions/*.txt, validates them and writes supabase/seed.sql.
// Line format:  pitanje | točan odgovor | drugi prihvaćeni odgovori (;) | dva netočna (;)
// Re-running is safe: existing questions keep their usage counters.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'questions');
const CATS = ['hrvatska', 'opce', 'nogomet', 'sport', 'geografija', 'matematika'];

const norm = (s) =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd').replace(/dj/g, 'd')
    .replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();
const sql = (s) => `'${s.replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `array[${a.map(sql).join(', ')}]::text[]` : `'{}'::text[]`);

const seen = new Map();
const rows = [];
const problems = [];
const counts = {};

for (const cat of CATS) {
  const file = path.join(dir, `${cat}.txt`);
  if (!fs.existsSync(file)) { problems.push(`missing ${cat}.txt`); continue; }
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  counts[cat] = 0;
  lines.forEach((line, i) => {
    const where = `${cat}.txt:${i + 1}`;
    if (!line.trim() || line.trimStart().startsWith('#')) return;
    const parts = line.split('|').map((p) => p.trim());
    if (parts.length !== 4) return problems.push(`${where} needs 4 fields, has ${parts.length}`);
    const [q, a, altRaw, wrongRaw] = parts;
    const aliases = altRaw ? altRaw.split(';').map((s) => s.trim()).filter(Boolean) : [];
    const wrong = wrongRaw.split(';').map((s) => s.trim()).filter(Boolean);
    if (!q || !a) return problems.push(`${where} empty question/answer`);
    if (wrong.length !== 2) return problems.push(`${where} needs exactly 2 wrong answers`);
    const accepted = [a, ...aliases].map(norm);
    for (const w of wrong) if (accepted.includes(norm(w))) problems.push(`${where} wrong answer "${w}" is also accepted`);
    if (norm(wrong[0]) === norm(wrong[1])) problems.push(`${where} both wrong answers are the same`);
    const key = norm(q);
    if (seen.has(key)) return problems.push(`${where} duplicate of ${seen.get(key)}`);
    seen.set(key, where);
    counts[cat]++;
    rows.push(`(${sql(cat)}, ${sql(q)}, ${sql(a)}, ${arr(aliases)}, ${arr(wrong)})`);
  });
}

if (problems.length) {
  console.error(problems.join('\n'));
  console.error(`\n${problems.length} problem(s) — seed not written.`);
  process.exit(1);
}

const out = [
  '-- Generated by scripts/build-questions.mjs — edit questions/*.txt instead.',
  'insert into public.questions (category, question, answer, aliases, wrong) values',
  rows.join(',\n'),
  'on conflict (question) do update set category = excluded.category, answer = excluded.answer,',
  '  aliases = excluded.aliases, wrong = excluded.wrong;',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), out);
console.log(counts, `total ${rows.length}`);
