// Reads questions/*.txt, validates them and writes supabase/seed.sql.
// Line format:  pitanje | točan odgovor | drugi prihvaćeni odgovori (;) | dva netočna (;)
// Re-running is safe: existing questions keep their usage counters.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'questions');
// [file name, category, usage]  usage: all = anywhere, open = typed rounds only, board = A/B/C board only
const FILES = [
  ['hrvatska', 'hrvatska', 'all'],
  ['opce', 'opce', 'all'],
  ['nogomet', 'nogomet', 'all'],
  ['sport', 'sport', 'all'],
  ['geografija', 'geografija', 'all'],
  ['matematika', 'matematika', 'all'],
  ['rijeci', 'hrvatska', 'all'],
  ['igrice_brzi', 'igrice', 'open'],
  ['igrice_ploca', 'igrice', 'board'],
];

const norm = (s) =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd').replace(/dj/g, 'd')
    .replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();
const sql = (s) => `'${s.replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `array[${a.map(sql).join(', ')}]::text[]` : `'{}'::text[]`);

const seen = new Map();
const rows = [];
const problems = [];
const counts = {};

for (const [fname, cat, usage] of FILES) {
  const file = path.join(dir, `${fname}.txt`);
  if (!fs.existsSync(file)) { problems.push(`missing ${fname}.txt`); continue; }
  const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);
  counts[fname] = 0;
  lines.forEach((line, i) => {
    const where = `${fname}.txt:${i + 1}`;
    if (!line.trim() || line.trimStart().startsWith('#')) return;
    const parts = line.split('|').map((p) => p.trim());
    if (parts.length !== 4) return problems.push(`${where} needs 4 fields, has ${parts.length}`);
    const [q, a, altRaw, wrongRaw] = parts;
    const aliases = altRaw ? altRaw.split(';').map((s) => s.trim()).filter(Boolean) : [];
    const wrong = wrongRaw.split(';').map((s) => s.trim()).filter(Boolean);
    if (!q || !a) return problems.push(`${where} empty question/answer`);
    if (wrong.length !== 2) return problems.push(`${where} needs exactly 2 wrong answers`);
    const accepted = [a, ...aliases].map(norm);
    for (const w of wrong) if (accepted.includes(norm(w))) problems.push(`${where} wrong answer "${w}" is also accepted`);
    if (norm(wrong[0]) === norm(wrong[1])) problems.push(`${where} both wrong answers are the same`);
    const key = norm(q);
    if (seen.has(key)) return problems.push(`${where} duplicate of ${seen.get(key)}`);
    seen.set(key, where);
    counts[fname]++;
    rows.push(`(${sql(cat)}, ${sql(q)}, ${sql(a)}, ${arr(aliases)}, ${arr(wrong)}, ${sql(usage)})`);
  });
}

// Lyric questions: izvođač | naslov | stih s ___ | odgovor | prihvaćeni (;) | netočni (;)
const lyricFile = path.join(dir, 'stihovi.txt');
counts.stihovi = 0;
if (fs.existsSync(lyricFile)) {
  fs.readFileSync(lyricFile, 'utf8').split(/\r?\n/).forEach((line, i) => {
    const where = `stihovi.txt:${i + 1}`;
    if (!line.trim() || line.trimStart().startsWith('#')) return;
    const parts = line.split('|').map((p) => p.trim());
    if (parts.length !== 6) return problems.push(`${where} needs 6 fields, has ${parts.length}`);
    const [artist, title, verse, a, altRaw, wrongRaw] = parts;
    if (!verse.includes('___')) return problems.push(`${where} verse needs ___ where the missing word goes`);
    const aliases = altRaw ? altRaw.split(';').map((x) => x.trim()).filter(Boolean) : [];
    const wrong = wrongRaw.split(';').map((x) => x.trim()).filter(Boolean);
    if (!a) return problems.push(`${where} missing answer`);
    if (wrong.length !== 2) return problems.push(`${where} needs exactly 2 wrong answers`);
    const q = `Nadopuni stih (${artist} – ${title}): „${verse}”`;
    const key = norm(q);
    if (seen.has(key)) return problems.push(`${where} duplicate of ${seen.get(key)}`);
    seen.set(key, where);
    counts.stihovi++;
    rows.push(`(${sql('stihovi')}, ${sql(q)}, ${sql(a)}, ${arr(aliases)}, ${arr(wrong)}, 'board')`);
  });
}

if (problems.length) {
  console.error(problems.join('\n'));
  console.error(`\n${problems.length} problem(s) — seed not written.`);
  process.exit(1);
}

const out = [
  '-- Generated by scripts/build-questions.mjs — edit questions/*.txt instead.',
  'insert into public.questions (category, question, answer, aliases, wrong, usage) values',
  rows.join(',\n'),
  'on conflict (question) do update set category = excluded.category, answer = excluded.answer,',
  '  aliases = excluded.aliases, wrong = excluded.wrong, usage = excluded.usage;',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), out);
console.log(counts, `total ${rows.length}`);

// Songs: regija | izvođač | naslov | deezer_id
const songRows = [];
const songProblems = [];
const songSeen = new Set();
const songFile = path.join(dir, 'pjesme.txt');
if (fs.existsSync(songFile)) {
  fs.readFileSync(songFile, 'utf8').split(/\r?\n/).forEach((line, i) => {
    if (!line.trim() || line.trimStart().startsWith('#')) return;
    const [region, artist, title, id] = line.split('|').map((x) => x.trim());
    const where = `pjesme.txt:${i + 1}`;
    if (!['balkan', 'svijet'].includes(region)) return songProblems.push(`${where} region must be balkan or svijet`);
    if (!artist || !title) return songProblems.push(`${where} missing artist/title`);
    if (!/^\d+$/.test(id ?? '')) return songProblems.push(`${where} missing Deezer ID`);
    const key = norm(artist + ' ' + title);
    if (songSeen.has(key)) return songProblems.push(`${where} duplicate song`);
    songSeen.add(key);
    songRows.push(`(${sql(region)}, ${sql(artist)}, ${sql(title)}, ${id})`);
  });
}
if (songProblems.length) {
  console.error(songProblems.join('\n'));
  process.exit(1);
}
if (songRows.length) {
  fs.writeFileSync(path.join(root, 'supabase', 'seed_songs.sql'), [
    '-- Generated by scripts/build-questions.mjs — edit questions/pjesme.txt instead.',
    'insert into public.songs (region, artist, title, deezer_id) values',
    songRows.join(',\n'),
    'on conflict (artist, title) do update set region = excluded.region, deezer_id = excluded.deezer_id;',
    '',
  ].join('\n'));
  console.log(`songs ${songRows.length}`);
}
